import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { randomSource, shuffle, canonicalRows, neighbours } from "./util.mjs";
import { geometry, solve } from "./model.mjs";
export const SEED = 0x414b4152;
export function generate() {
  const random = randomSource(SEED),
    levels = [],
    seen = new Set(),
    stats = [];
  for (const n of [5, 6, 7]) {
    let attempts = 0,
      accepted = 0;
    while (accepted < 20) {
      if (++attempts > 10000) throw Error("Generation budget exceeded");
      const cells = Array.from({ length: n * n }, () =>
          random() < 0.29 ? -1 : -2,
        ),
        level = { n, cells },
        g = geometry(level);
      if (
        g.white.length < n * n * 0.58 ||
        g.white.some((i) => g.visible[i].length === 1)
      )
        continue;
      const answer = cells.map(() => 0);
      for (const i of shuffle(g.white, random))
        if (!g.visible[i].some((j) => answer[j])) answer[i] = 1;
      if (answer.reduce((s, v) => s + v, 0) < 4) continue;
      for (let i = 0; i < cells.length; i++)
        if (cells[i] === -1)
          cells[i] = neighbours(i, n).reduce((s, j) => s + answer[j], 0);
      let proof = solve(level);
      if (!proof.complete || proof.count !== 1) continue;
      for (const i of shuffle(
        cells.flatMap((v, i) => (v >= 0 ? [i] : [])),
        random,
      ).slice(0, Math.floor(n * n * 0.13))) {
        const v = cells[i];
        cells[i] = -1;
        const next = solve(level);
        if (next.complete && next.count === 1) proof = next;
        else cells[i] = v;
      }
      const rows = Array.from({ length: n }, (_, r) =>
          cells
            .slice(r * n, (r + 1) * n)
            .map((v) => (v === -2 ? "." : v === -1 ? "#" : String(v))),
        ),
        key = canonicalRows(rows);
      if (seen.has(key)) continue;
      seen.add(key);
      accepted++;
      levels.push({
        ...level,
        name: `${n}×${n} · ${accepted}`,
        solution: proof.solution,
        proof: { nodes: proof.nodes },
      });
    }
    stats.push({ n, attempts, accepted });
  }
  return { levels, stats };
}
export function serialize(result) {
  return `// Generated by node game/akari/generate.mjs; seed ${SEED}.\nexport const statistics = ${JSON.stringify(result.stats)};\nexport const levels = ${JSON.stringify(result.levels, null, 2)};\n`;
}
if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const result = generate(),
    text = serialize(result),
    path = new URL("./levels.mjs", import.meta.url);
  if (process.argv.includes("--check")) {
    if (readFileSync(path, "utf8") !== text) throw Error("Dataset differs");
  } else writeFileSync(path, text);
  console.log(JSON.stringify(result.stats));
}
