import assert from "node:assert/strict";
import { fresh, options, roll, stop, heights } from "./model.mjs";
let s = fresh();
s.dice = [1, 1, 1, 1];
assert.equal(options(s)[0].temp[0], 2);
s.temp = { 0: 1, 1: 1 };
s.dice = [1, 3, 2, 4];
assert(options(s).some((o) => o.temp[2]));
assert(options(s).some((o) => o.temp[4]));
s = fresh();
s.temp = { 0: 3 };
assert.equal(s.claimed[0], -1);
stop(s);
assert.equal(s.claimed[0], 0);
s = fresh();
s.temp = { 0: 1, 1: 1, 2: 1 };
roll(s, [6, 6, 6, 6]);
assert.deepEqual(s.temp, {});
assert.equal(s.player, 1);
s = fresh();
s.claimed[0] = s.claimed[1] = 0;
s.temp = { 2: heights[2] };
stop(s);
assert.equal(s.winner, 0);
console.log("Can’t Stop model: passed");
