const shapes = [];
for (const original of baseShapes)
  for (let turn = 0; turn < 4; turn++)
    for (let flip = 0; flip < 2; flip++) {
      let p = original.map(([r, c]) => [r, flip ? -c : c]);
      for (let t = 0; t < turn; t++) p = p.map(([r, c]) => [c, -r]);
      const mr = Math.min(...p.map((x) => x[0])),
        mc = Math.min(...p.map((x) => x[1]));
      p = p
        .map(([r, c]) => [r - mr, c - mc])
        .sort((a, b) => a[0] - b[0] || a[1] - b[1]);
      if (!shapes.some((s) => JSON.stringify(s) === JSON.stringify(p)))
        shapes.push(p);
    }
function tile(n, random) {
  const occupied = Array(n * n).fill(false),
    regions = [];
  let nodes = 0;
  function visit() {
    if (++nodes > 5000) return false;
    const first = occupied.indexOf(false);
    if (first < 0) return true;
    const r = Math.floor(first / n),
      c = first % n;
    for (const shape of shuffle(shapes, random)) {
      for (const anchor of shuffle(shape, random)) {
        const cells = shape.map(([sr, sc]) => [
          sr + r - anchor[0],
          sc + c - anchor[1],
        ]);
        if (
          cells.some(
            ([r, c]) =>
              r < 0 || c < 0 || r >= n || c >= n || occupied[r * n + c],
          )
        )
          continue;
        const ids = cells.map(([r, c]) => r * n + c);
        ids.forEach((i) => (occupied[i] = true));
        regions.push(ids);
        if (visit()) return true;
        regions.pop();
        ids.forEach((i) => (occupied[i] = false));
      }
    }
    return false;
  }
  return visit() ? regions : null;
}
export function canonical(level) {
  const side = 2 * level.n - 1,
    rows = Array.from({ length: side }, () => Array(side).fill("."));
  for (const c of level.centers) rows[c.r2][c.c2] = "o";
  return canonicalRows(rows);
}
export function generate() {
  const random = randomSource(SEED),
    levels = [],
    seen = new Set(),
    stats = [];
  for (const n of [4, 5, 6]) {
    let attempts = 0,
      accepted = 0;
    while (accepted < 20) {
      if (++attempts > 20000) throw Error("Generation budget exceeded");
      const regions = tile(n, random);
      if (
        !regions ||
        regions.length < 3 ||
        regions.length > n * n * 0.5 ||
        regions.filter((r) => r.length === 1).length > n * n * 0.2
      )
        continue;
      let nonrect = 0;
      const centers = regions.map((cells) => {
        const rs = cells.map((i) => Math.floor(i / n)),
          cs = cells.map((i) => i % n),
          rmin = Math.min(...rs),
          rmax = Math.max(...rs),
          cmin = Math.min(...cs),
          cmax = Math.max(...cs);
        if ((rmax - rmin + 1) * (cmax - cmin + 1) !== cells.length) nonrect++;
        return { r2: rmin + rmax, c2: cmin + cmax };
      });
      if (!nonrect) continue;
      const level = { n, centers },
        key = canonical(level);
      if (seen.has(key)) continue;
      const proof = solve(level);
      if (!proof.complete || proof.count !== 1) continue;
      if (!inspect(level, boundaries(level, proof.solution)).solved)
        throw Error("Invalid generated partition");
      seen.add(key);
      accepted++;
      levels.push({
        ...level,
        name: `${n}×${n} · ${accepted}`,
        solution: boundaries(level, proof.solution),
        proof: { nodes: proof.nodes, regions: proof.regions },
      });
    }
    stats.push({ n, attempts, accepted });
  }
  return { levels, stats };
}
export function serialize(result) {
  return `// Generated by node game/galaxies/generate.mjs; seed ${SEED}.\nexport const statistics = ${JSON.stringify(result.stats)};\nexport const levels = ${JSON.stringify(result.levels, null, 2)};\n`;
}
if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const result = generate(),
    text = serialize(result),
    path = new URL("./levels.mjs", import.meta.url);
  if (process.argv.includes("--check")) {
    if (readFileSync(path, "utf8") !== text) throw Error("Dataset differs");
  } else writeFileSync(path, text);
  console.log(JSON.stringify(result.stats));
}
