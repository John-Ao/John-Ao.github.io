import { writeFileSync, readFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { randomSource, shuffle, canonicalRows } from "./util.mjs";
import { geometry, solve } from "./model.mjs";
export const SEED = 0x48415348;
export function generate() {
  const random = randomSource(SEED),
    levels = [],
    seen = new Set(),
    stats = [];
  for (const n of [5, 7, 9]) {
    let attempts = 0,
      accepted = 0;
    while (accepted < 20) {
      if (++attempts > 20000) throw Error("Search budget exceeded");
      const axis =
          n === 5 ? [0, 2, 4] : n === 7 ? [0, 2, 4, 6] : [0, 2, 4, 6, 8],
        points = axis.flatMap((r) => axis.map((c) => ({ r, c, value: 0 }))),
        count =
          n === 5
            ? 6 + Math.floor(random() * 3)
            : n === 7
              ? 9 + Math.floor(random() * 4)
              : 12 + Math.floor(random() * 5);
      const islands = shuffle(points, random)
          .slice(0, count)
          .sort((a, b) => a.r - b.r || a.c - b.c),
        level = { n, islands },
        g = geometry(level),
        parent = islands.map((_, i) => i);
      function root(i) {
        while (parent[i] !== i) i = parent[i];
        return i;
      }
      const values = g.edges.map(() => 0);
      for (const i of shuffle(
        g.edges.map((_, i) => i),
        random,
      )) {
        const e = g.edges[i];
        if (root(e.a) === root(e.b) || g.crossing[i].some((j) => values[j]))
          continue;
        values[i] = random() < 0.48 ? 2 : 1;
        parent[root(e.a)] = root(e.b);
      }
      if (islands.some((_, i) => root(i) !== root(0))) continue;
      for (const i of shuffle(
        g.edges.map((_, i) => i),
        random,
      ))
        if (
          !values[i] &&
          random() < 0.15 &&
          !g.crossing[i].some((j) => values[j])
        )
          values[i] = 1;
      g.incident.forEach(
        (ids, i) => (islands[i].value = ids.reduce((s, j) => s + values[j], 0)),
      );
      const rows = Array.from({ length: n }, () => Array(n).fill("."));
      for (const p of islands) rows[p.r][p.c] = p.value;
      const key = canonicalRows(rows);
      if (seen.has(key)) continue;
      const proof = solve(level);
      if (!proof.complete || proof.count !== 1) continue;
      seen.add(key);
      accepted++;
      levels.push({
        ...level,
        solution: proof.solution,
        proof: { nodes: proof.nodes },
        name: `${n}×${n} · ${accepted}`,
      });
    }
    stats.push({ n, attempts, accepted });
  }
  return { levels, stats };
}
export function serialize(result) {
  return `// Generated by node game/hashi/generate.mjs; seed ${SEED}.\nexport const statistics = ${JSON.stringify(result.stats)};\nexport const levels = ${JSON.stringify(result.levels, null, 2)};\n`;
}
if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const result = generate(),
    text = serialize(result),
    path = new URL("./levels.mjs", import.meta.url);
  if (process.argv.includes("--check")) {
    if (readFileSync(path, "utf8") !== text) throw Error("Dataset differs");
  } else writeFileSync(path, text);
  console.log(JSON.stringify(result.stats));
}
