import { writeFileSync, readFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { analyzeSolutions, canonicalGrid, clues } from "./core.mjs";
import { curatedLevels } from "./curated.mjs";

export const SEED = 0x4e4f4e4f;
export const PER_SIZE = 40;
function randomSource(seed) {
  let value = seed >>> 0;
  return () => {
    value = (Math.imul(value, 1664525) + 1013904223) >>> 0;
    return value / 4294967296;
  };
}
export function generateLevels() {
  const random = randomSource(SEED),
    seen = new Set(curatedLevels.map((l) => canonicalGrid(l.grid)));
  const levels = [],
    statistics = [];
  for (const size of [5, 7, 10]) {
    let attempts = 0,
      accepted = 0;
    while (accepted < PER_SIZE) {
      attempts++;
      if (attempts > 100000)
        throw new Error(`Not enough ${size}×${size} puzzles`);
      const density = 0.38 + random() * 0.27;
      const grid = Array.from({ length: size }, () =>
        Array.from({ length: size }, () => +(random() < density)),
      );
      const filled = grid.flat().reduce((sum, value) => sum + value, 0);
      if (filled < size * size * 0.32 || filled > size * size * 0.7) continue;
      const hints = clues(grid),
        lines = [...hints.rows, ...hints.cols];
      // No empty/full lines; require several separated runs, not just a solid block.
      if (lines.some((line) => line[0] === 0 || line[0] === size)) continue;
      if (lines.filter((line) => line.length >= 2).length < size) continue;
      const key = canonicalGrid(grid);
      if (seen.has(key)) continue;
      const proof = analyzeSolutions(grid);
      if (proof.count !== 1) continue;
      seen.add(key);
      accepted++;
      levels.push({
        name: `${size} × ${size} · ${String(accepted).padStart(2, "0")}`,
        grid,
        proof: { branches: proof.branches, passes: proof.passes },
      });
    }
    statistics.push({ size, accepted, attempts });
  }
  return { levels, statistics };
}
export function serializeGenerated({ levels, statistics }) {
  // Compact rows keep the offline dataset reviewable; the browser does no search.
  const data = levels.map(({ name, grid, proof }) => ({
    name,
    rows: grid.map((row) => row.join("")),
    proof,
  }));
  return `// Generated by node game/nonogram/generate.mjs; do not hand-edit.\n// Seed: ${SEED}; ${JSON.stringify(statistics)}\nexport const generation = ${JSON.stringify({ seed: SEED, perSize: PER_SIZE, statistics })};\nconst data = ${JSON.stringify(data, null, 2)};\nexport const generatedLevels = data.map(({name, rows, proof}) => ({name, grid: rows.map(row => [...row].map(Number)), proof}));\n`;
}
if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const generated = generateLevels(),
    output = serializeGenerated(generated),
    path = new URL("./levels.generated.mjs", import.meta.url);
  if (process.argv.includes("--check")) {
    if (readFileSync(path, "utf8") !== output)
      throw new Error("Generated dataset differs; regenerate it.");
    console.log("Generated dataset is reproducible.");
  } else writeFileSync(path, output);
  console.log(JSON.stringify(generated.statistics));
}
