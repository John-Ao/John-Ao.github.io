// Offline only: deterministic region search, clue deletion, exhaustive proof.
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { levels, geometry, validLoop, enumerateSolutions } from "./model.mjs";
import {
  seededRandom,
  shuffled,
  boundary,
  canonicalLoop,
} from "./generation.mjs";

const seed = 0x534c2026;
const random = seededRandom(seed);
const generated = [];
const seen = new Set(
  levels.slice(0, 8).map((l) => canonicalLoop(l.n, l.solution)),
);
const budget = 12000;
for (const n of [4, 5, 6]) {
  let accepted = 0,
    attempts = 0;
  const { cells } = geometry(n),
    emptyClues = Array(n * n).fill(null);
  while (accepted < 32) {
    if (++attempts > 20000)
      throw Error(`Failed to find 32 puzzles of size ${n}`);
    const region = new Set([Math.floor(random() * n * n)]);
    const area = Math.floor(n * n * (0.3 + random() * 0.45));
    while (region.size < area) {
      const candidates = new Set();
      for (const i of region) {
        const r = Math.floor(i / n),
          c = i % n;
        for (const [dr, dc] of [
          [0, 1],
          [1, 0],
          [0, -1],
          [-1, 0],
        ]) {
          const y = r + dr,
            x = c + dc,
            j = y * n + x;
          if (y >= 0 && x >= 0 && y < n && x < n && !region.has(j))
            candidates.add(j);
        }
      }
      let grew = false;
      for (const j of shuffled(candidates, random)) {
        region.add(j);
        if (validLoop(boundary(n, region), n, emptyClues)) {
          grew = true;
          break;
        }
        region.delete(j);
      }
      if (!grew) break;
    }
    const solution = boundary(n, region);
    const signature = canonicalLoop(n, solution);
    if (seen.has(signature) || !validLoop(solution, n, emptyClues)) continue;
    const clues = cells.map((ids) =>
      ids.reduce((sum, i) => sum + solution[i], 0),
    );
    let proof = enumerateSolutions(n, clues, { budget });
    if (proof.exhausted || proof.count !== 1) continue;
    const desired = Math.ceil(n * n * (0.4 + random() * 0.15));
    let remaining = n * n;
    for (const i of shuffled(
      Array.from({ length: n * n }, (_, j) => j),
      random,
    )) {
      if (remaining <= desired) break;
      const old = clues[i];
      clues[i] = null;
      proof = enumerateSolutions(n, clues, { budget });
      if (proof.exhausted || proof.count !== 1) clues[i] = old;
      else remaining--;
    }
    if (remaining > Math.floor(n * n * 0.8)) continue;
    proof = enumerateSolutions(n, clues, { budget });
    if (proof.exhausted || proof.count !== 1)
      throw Error("Final uniqueness proof failed");
    seen.add(signature);
    accepted++;
    generated.push({
      name: `${n}×${n} · ${String(accepted).padStart(2, "0")}`,
      n,
      solution,
      clues,
    });
  }
  console.log(
    `${n}×${n}: ${accepted} unique puzzles from ${attempts} candidate regions`,
  );
}
const text = `// Generated by node game/slitherlink/generate.mjs. Seed: ${seed}. Do not edit by hand.\nexport const generatedLevels = ${JSON.stringify(generated, null, 2)};\n`;
const outputPath = fileURLToPath(
  new URL("./generated-levels.mjs", import.meta.url),
);
if (process.argv.includes("--check")) {
  if (readFileSync(outputPath, "utf8") !== text)
    throw Error(
      "Generated data differs: rerun generate.mjs and review the change",
    );
  console.log("Reproducibility check passed; no files changed.");
} else writeFileSync(outputPath, text);
console.log(
  `${process.argv.includes("--check") ? "Verified" : "Wrote"} ${generated.length} generated puzzles; ${generated.length + 8} total.`,
);
