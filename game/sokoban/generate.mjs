import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { randomSource, shuffle, canonicalRows } from "./util.mjs";
import {
  adjacent,
  directions,
  move,
  pull,
  reachable,
  solve,
} from "./model.mjs";
export const SEED = 0x534f4b4f;
export function canonical(level) {
  const rows = Array.from({ length: level.n }, (_, r) =>
    Array.from({ length: level.n }, (_, c) => {
      const i = r * level.n + c;
      if (level.walls[i]) return "#";
      if (level.player === i) return level.goals.includes(i) ? "+" : "@";
      if (level.boxes.includes(i)) return level.goals.includes(i) ? "*" : "$";
      return level.goals.includes(i) ? "." : " ";
    }),
  );
  return canonicalRows(rows);
}
export function generate() {
  const random = randomSource(SEED),
    levels = [],
    seen = new Set(),
    layouts = new Set(),
    stats = [];
  for (const n of [6, 7, 8]) {
    let attempts = 0,
      accepted = 0;
    while (accepted < 20) {
      if (++attempts > 20000) throw Error("Generation budget exceeded");
      const walls = Array.from(
          { length: n * n },
          (_, i) =>
            +(
              Math.floor(i / n) === 0 ||
              Math.floor(i / n) === n - 1 ||
              i % n === 0 ||
              i % n === n - 1 ||
              random() < 0.16
            ),
        ),
        floor = walls.flatMap((v, i) => (v ? [] : [i]));
      if (floor.length < (n - 2) ** 2 * 0.72) continue;
      const layout = canonicalRows(
        Array.from({ length: n }, (_, r) => walls.slice(r * n, (r + 1) * n)),
      );
      if (layouts.has(layout)) continue;
      const choices = shuffle(floor, random),
        goals = choices.slice(0, n === 8 ? 3 : 2).sort((a, b) => a - b),
        goalPlayer = choices[goals.length],
        level = { n, walls, goals };
      if (
        reachable(level, { player: goalPlayer, boxes: [] }).size !==
        floor.length
      )
        continue;
      let state = { player: goalPlayer, boxes: goals.slice() },
        reverse = [];
      for (let turn = 0; turn < 32; turn++) {
        const reach = reachable(level, state),
          options = [];
        for (const box of state.boxes)
          for (const dir of Object.keys(directions)) {
            const stand = adjacent(box, dir, n);
            if (!reach.has(stand)) continue;
            const next = pull(level, { ...state, player: stand }, dir);
            if (next) options.push({ next, walk: reach.get(stand), dir });
          }
        if (!options.length) break;
        const chosen = options[Math.floor(random() * options.length)];
        reverse.push({ walk: chosen.walk, pull: chosen.dir });
        state = chosen.next;
      }
      if (state.boxes.filter((i) => !goals.includes(i)).length < 2) continue;
      Object.assign(level, state);
      const key = canonical(level);
      if (seen.has(key)) continue;
      const proof = solve(level);
      if (
        !proof.complete ||
        !proof.solvable ||
        proof.minimumPushes < (n === 6 ? 4 : n === 7 ? 6 : 8)
      )
        continue;
      seen.add(key);
      layouts.add(layout);
      accepted++;
      levels.push({
        ...level,
        name: `${n}×${n} · ${accepted}`,
        solution: proof.solution,
        proof: { minimumPushes: proof.minimumPushes, nodes: proof.nodes },
        construction: { goalPlayer, reverse },
      });
    }
    stats.push({ n, attempts, accepted });
  }
  return { levels, stats };
}
export function serialize(result) {
  return `// Generated by node game/sokoban/generate.mjs; seed ${SEED}.\nexport const statistics = ${JSON.stringify(result.stats)};\nexport const levels = ${JSON.stringify(result.levels, null, 2)};\n`;
}
if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const result = generate(),
    text = serialize(result),
    path = new URL("./levels.mjs", import.meta.url);
  if (process.argv.includes("--check")) {
    if (readFileSync(path, "utf8") !== text) throw Error("Dataset differs");
  } else writeFileSync(path, text);
  console.log(JSON.stringify(result.stats));
}
