import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { solve } from './model.mjs';
export const collections = [
  ['microban', 'Microban', 'm1.txt'],
  ['microban-ii', 'Microban II', 'm2.txt'],
  ['sasquatch', 'Sasquatch', 's1.txt'],
];
export function parseCollection(text, id, group) {
  const pieces = text.replaceAll('\r', '').split(/;\s*(\d+)\s*\n/), result = [];
  for (let k = 1; k < pieces.length; k += 2) {
    const number = +pieces[k], rows = pieces[k + 1].split('\n').filter(row => row.includes('#'));
    const n = Math.max(rows.length, ...rows.map(r => r.length));
    if (n > 16) continue;
    const l = { id: `${id}-${number}`, group, name: `${group} · ${number}`, sourceNumber: number,
      rows, n, walls: Array(n*n).fill(1), goals: [], boxes: [], player: -1 };
    let players = 0;
    rows.forEach((row,r) => [...row].forEach((c,col) => {
      if (!'# .$*@+'.includes(c)) throw Error(`Unexpected symbol in ${l.id}`);
      const i=r*n+col;
      l.walls[i]=+(c==='#');
      if ('.*+'.includes(c)) l.goals.push(i);
      if ('$*'.includes(c)) l.boxes.push(i);
      if ('@+'.includes(c)) {l.player=i; players++;}
    }));
    if (players !== 1 || l.boxes.length !== l.goals.length) throw Error(`Invalid ${l.id}`);
    const seen = new Set([l.player]), queue = [l.player];
    for (const i of queue) {
      if (i<n || i>=n*(n-1) || i%n===0 || i%n===n-1) throw Error(`Open boundary ${l.id}`);
      for (const j of [i-n,i+n,i-1,i+1]) if(!l.walls[j]&&!seen.has(j)){seen.add(j);queue.push(j);}
    }
    if (![...l.boxes,...l.goals].every(i=>seen.has(i))) continue;
    l.walls = l.walls.map((_,i)=>+!seen.has(i));
    result.push(l);
  }
  return result;
}
export function build() {
  const result=[];
  for (const [id,group] of collections) {
    const raw=readFileSync(new URL(`./sources/${id}.txt`,import.meta.url),'utf8');
    const selected=[];
    for(const l of parseCollection(raw,id,group)) {
      if(l.boxes.length<3 || l.boxes.length>6) continue;
      const proof=solve(l,{budget:20000});
      if(!proof.solvable || proof.minimumPushes<18)continue;
      selected.push({...l,solution:proof.solution,proof:{minimumPushes:proof.minimumPushes,nodes:proof.nodes}});
    }
    selected.sort((a,b)=>a.proof.minimumPushes-b.proof.minimumPushes || a.sourceNumber-b.sourceNumber);
    result.push(...selected);
    console.log(`${group}: ${selected.length}`);
  }
  return result;
}
if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const text='// David W. Skinner. Freely distributed with attribution; see sources/README.md.\n// Generated by node game/sokoban/import-levels.mjs\nexport const classicLevels = '+JSON.stringify(build(),null,2)+';\n';
  const path=new URL('./classic-levels.mjs',import.meta.url);
  if(process.argv.includes('--check')) {
    if(readFileSync(path,'utf8')!==text)throw Error('Dataset differs');
  } else writeFileSync(path,text);
}
