// Regenerate the two-character Git publication set without deleting local assets.
import fs from 'node:fs';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
const root=fileURLToPath(new URL('../',import.meta.url));
const selected=new Set(['anby','nicole']);
const read=p=>JSON.parse(fs.readFileSync(path.join(root,p),'utf8'));
const write=(p,value)=>fs.writeFileSync(path.join(root,p),JSON.stringify(value,null,2)+'\n');
function full(p){
 const local=p.replace(/\.json$/,'.local.json');
 if(!fs.existsSync(path.join(root,local)))fs.copyFileSync(path.join(root,p),path.join(root,local));
 return read(local);
}
const roster=full('roster.json').filter(a=>selected.has(a.id));
const catalog=full('assets/models/catalog.json').filter(a=>selected.has(a.agentId));
const coverage=full('assets/coverage.json');
write('roster.json',roster);write('assets/models/catalog.json',catalog);
write('assets/coverage.json',{...coverage,releasedCount:roster.length,scope:'Published selection, not the complete released roster',characters:coverage.characters.filter(c=>selected.has(c.id)),riggedModelCount:catalog.length,animatedCharacterCount:catalog.length,skeletalClipCount:catalog.reduce((n,c)=>n+c.clips.length,0)});
const files=new Set(['assets/coverage.json','assets/models/catalog.json','assets/models/provenance.json','assets/models/shading-sources.json']);
for(const a of roster){
 for(const p of [a.portrait,a.splash,a.factionIcon,...a.cinemaImages])files.add(p.replace(/^\.\//,''));
 for(const suffix of ['.mp4','-poster.webp'])files.add(`assets/motion/${a.id}${suffix}`);
}
for(const file of fs.readdirSync(path.join(root,'assets/ui')))files.add(`assets/ui/${file}`);
for(const e of catalog){
 const dir=`assets/models/${e.key}/`;
 for(const clip of e.clips){
  const p=dir+clip.id+'.gltf';files.add(p);
  const g=read(p);for(const ref of [...g.buffers,...g.images])files.add(dir+ref.uri);
 }
 for(const part of ['Body','Face','Hair','Weapon']){
  const special=e.key==='anby'&&part==='Weapon'?'Weapon_Fire':e.key==='nicole'&&part==='Body'?'Body_T':part;
  const suffix=e.key==='nicole'&&part==='Body'?'_CN':'';
  files.add(dir+`shading/MAT_${e.prefix}_${special}_UI.json`);
  files.add(dir+'shading/'+(part==='Face'?'Famale_Face_lightmap.png':`${e.prefix}_${part}_N${suffix}.png`));
  if(part!=='Face')files.add(dir+`shading/${e.prefix}_${part}_M${suffix}.png`);
 }
 files.add(dir+'shading/'+(e.key==='anby'?'Metal_MatCap.png':'Nostradamus_Body_MatCap_Tex.png'));
}
for(const p of ['assets/models/provenance.json','assets/models/shading-sources.json'])write(p,full(p).filter(e=>files.has(e.file)));
full('assets/motion/provenance.json');
// Original recording provenance is small; preserve it locally, with research notes in RESEARCH.md.
for(const p of files)if(!fs.existsSync(path.join(root,p)))throw Error('Missing published asset: '+p);
fs.writeFileSync(path.join(root,'.gitignore'),`# Generated by scripts/prepare-publication.mjs. Files remain available locally.\n*.local.json\n/research/\n/preview*\n**/__pycache__/\n/assets/**\n!/assets/**/\n${[...files].sort().map(p=>'!/'+p).join('\n')}\n`);
console.log(`Publication: ${roster.length} characters, ${files.size} asset files. Full local manifests preserved.`);
